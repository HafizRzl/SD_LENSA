"""Compare what LENSA's detectors can actually detect vs. your object_catalog.

Two detectors: stock YOLO26n (Ultralytics, COCO's 80 classes — we did not train it) and the
road-hazard model we trained (train_hazards.py: broken_road, pothole). Only their classes
can ever fire. This script writes `detectable_classes.md` and prints a summary.

    python desktop-beta/list_classes.py
"""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).parent))
from ultralytics import YOLO
from lensa_rules import ObjectCatalog, _load

HERE = Path(__file__).parent


def norm(name: str) -> str:
    return name.lower().replace(" ", "_")


def main():
    model = YOLO(str(HERE / "models" / "yolo26n.pt"))
    coco = dict(sorted(model.names.items()))          # {0: 'person', ...}
    coco_norm = {norm(v) for v in coco.values()}
    road = HERE / "models" / "road_hazard_yolo26n.pt"
    road_names = sorted(norm(v) for v in YOLO(str(road)).names.values()) if road.exists() else []
    coco_norm |= set(road_names)

    cat = ObjectCatalog.load(_load("rules/object_catalog.yaml"))
    cat_classes = list(cat.by_class.keys())
    live = [c for c in cat_classes if c in coco_norm]
    dormant = [c for c in cat_classes if c not in coco_norm]
    extra = sorted(coco_norm - set(cat_classes))

    out = []
    out.append("# What LENSA can actually detect")
    out.append("")
    out.append("> Auto-generated by `list_classes.py`. Two detectors run in the beta:")
    out.append("> - `models/yolo26n.pt` — stock YOLO26n, pretrained by Ultralytics on COCO (80 classes).")
    out.append("> - `models/road_hazard_yolo26n.pt` — trained by us (`train_hazards.py`): "
               + (", ".join(f"`{c}`" for c in road_names) or "not trained yet") + ".")
    out.append(f"> Your curated priorities/labels live in `assets/context/rules/object_catalog.yaml`.")
    out.append("")
    out.append(f"## Your catalog vs. the model — {len(live)}/{len(cat_classes)} entries are live")
    out.append("")
    out.append("### Live — in your catalog AND detectable by one of the two models")
    out.append("")
    for c in live:
        out.append(f"- `{c}` — {cat.label(c, 'ms')} (danger {cat.danger_weight(c)})")
    out.append("")
    out.append("### Dormant — in your catalog but no model detects it yet (needs training data)")
    out.append("")
    for c in dormant:
        out.append(f"- `{c}` — {cat.label(c, 'ms')} (danger {cat.danger_weight(c)})")
    out.append("")
    out.append("Each needs a labelled dataset and a training run like `train_hazards.py`.")
    out.append("")
    out.append("## All 80 COCO classes YOLO26n knows")
    out.append("")
    out.append(", ".join(f"`{norm(v)}`" for v in coco.values()))
    out.append("")
    out.append("### COCO classes not yet in your catalog (add weights if useful)")
    out.append("")
    out.append(", ".join(f"`{c}`" for c in extra))
    out.append("")
    (HERE / "detectable_classes.md").write_text("\n".join(out), encoding="utf-8")

    print(f"LIVE ({len(live)}/{len(cat_classes)}): {live}")
    print(f"DORMANT (need custom training): {dormant}")
    print("-> wrote desktop-beta/detectable_classes.md")


if __name__ == "__main__":
    main()
